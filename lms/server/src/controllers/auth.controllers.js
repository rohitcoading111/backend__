export const registerUser = async (req, res) => {
  try {
    // 1. Send registration data and uploaded file to the service
    const result = await registerUserService({
      ...req.body,
      file: req.file,
    });

    // 2. Get the tokens generated by the service
    const { accessToken, refreshToken } = result;

    // 3. Store refresh token in an HttpOnly cookie
    res.cookie("refreshToken", refreshToken, {
      httpOnly: true,
      sameSite: "lax",
      secure: process.env.NODE_ENV === "production",
      maxAge: 7 * 24 * 60 * 60 * 1000,
    });

    // 4. Send success response to the frontend
    return res.status(201).json({
      success: true,
      message: "User registered successfully",
      data: {
        accessToken,
      },
    });
  } catch (error) {
    // 5. Handle duplicate email or mobile number
    if (
      error.message === "User already exists" ||
      error.message === "Email or mobile number already exists" ||
      error.code === 11000
    ) {
      return res.status(409).json({
        success: false,
        message: "Email or mobile number already exists",
      });
    }

    // 6. Handle missing email and mobile number
    if (error.message === "Email or mobile number is required") {
      return res.status(400).json({
        success: false,
        message: error.message,
      });
    }

    // 7. Log unexpected errors on the server
    console.error("Register Controller Error:", error);

    // 8. Send a generic error to the client
    return res.status(500).json({
      success: false,
      message: "Internal server error",
    });
  }
};


